/** Large countries with no neighbour 6pm prices differently near them: south, north, west, east. */
const BOXES: readonly (readonly [string, number, number, number, number])[] = [
  ['AU', -44, -10.5, 112, 154],
  ['US', 24.5, 49, -125, -67],
  ['JP', 30, 45.6, 129.5, 146],
];

/** Every listed town once, read from the table above. */
const PLACES: readonly (readonly [string, Town])[] = Object.entries(TOWNS).flatMap(
  ([country, rows]) =>
    rows.flatMap((row) =>
      row.split(', ').map((pair) => {
        const [lat = '', lon = ''] = pair.split(' ');
        return [country, [Number(lat), Number(lon)] as Town] as const;
      }),
    ),
);

/** Kilometres between two points, near enough for choosing the nearest town. */
function distanceKm(a: Town, b: Town): number {
  const toRad = Math.PI / 180;
  const x = (b[1] - a[1]) * toRad * Math.cos(((a[0] + b[0]) / 2) * toRad);
  const y = (b[0] - a[0]) * toRad;
  return Math.sqrt(x * x + y * y) * 6371;
}

/** The ISO 3166-1 country at a point, or null where the list does not reach. */
export function countryAt(latitude: number, longitude: number): string | null {
  if (!Number.isFinite(latitude) || !Number.isFinite(longitude)) return null;
  if (Math.abs(latitude) > 90 || Math.abs(longitude) > 180) return null;
  const here: Town = [latitude, longitude];
  let nearest: string | null = null;
  let best = REACH_KM;
  for (const [country, town] of PLACES) {
    const km = distanceKm(here, town);
    if (km < best) [nearest, best] = [country, km];
  }
  if (nearest !== null) return nearest;
  const box = BOXES.find(
    ([, south, north, west, east]) =>
      latitude >= south && latitude <= north && longitude >= west && longitude <= east,
  );
  return box?.[0] ?? null;
}

/**
 * The currency spent where a photo was taken: đồng in Vietnam, the country's currency where 6pm
 * has a rate for it, else null.
 */
export function currencyAt(latitude: number, longitude: number): string | null {
  const country = countryAt(latitude, longitude);
  if (country === null) return null;
  return country === 'VN' ? 'VND' : (COUNTRY_CURRENCY[country] ?? null);
}
