/**
 * Copies the prototype's pure look logic (palettes, looks catalogue, atmosphere, sun, companion
 * lines) into a generated module, byte for byte, so the app's colours are the prototype's colours.
 *
 *   pnpm tsx tools/design/extract-prototype-logic.ts [--check]
 *
 * The prototype's logic class is evaluated in a sandbox (never executed against a page) and each
 * listed method's source is read with Function.prototype.toString.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import vm from 'node:vm';

const root = join(import.meta.dirname, '../..');
const source = join(root, 'design/prototype/6pm App.dc.html');
const target = join(root, 'packages/theme/src/generated/prototype-looks.generated.js');

/** Pure methods: they read only `this.state`/`this.props` through the look helpers below. */
const METHODS = [
  'hex',
  'mix',
  'palette',
  'themes',
  'rng',
  'appliedId',
  'activeId',
  'propThemeId',
  'cfgOf',
  'themeOf',
  'swOf',
  'sunFx',
  'sig',
  'atm',
  'paperCols',
  'premiumAtm',
  'iconPacks',
] as const;

const html = readFileSync(source, 'utf8');
const script = /<script type="text\/x-dc"[^>]*>([\s\S]*?)<\/script>/.exec(html)?.[1];
if (!script) throw new Error('No logic script found in the prototype');

const sandbox = vm.createContext({});
const Component = vm.runInContext(`class DCLogic {}\n${script}\n;Component`, sandbox) as {
  prototype: Record<string, unknown>;
};

const bodies = METHODS.map((name) => {
  const fn = Component.prototype[name];
  if (typeof fn !== 'function') throw new Error(`Prototype method missing: ${name}`);
  return `  ${(fn as (...args: unknown[]) => unknown).toString()}`;
});

const output = `// @generated by tools/design/extract-prototype-logic.ts from design/prototype/6pm App.dc.html.
// Do not edit: change the prototype and regenerate. The look engine in ../look-engine.ts wraps it.
/* eslint-disable */
// prettier-ignore
export const prototypeLooks = {
${bodies.join(',\n')}
};
`;

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) {
    console.error('prototype-looks.generated.js is stale: run tools/design/extract-prototype-logic.ts');
    process.exit(1);
  }
} else {
  writeFileSync(target, output);
  console.log(`wrote ${target} (${METHODS.length} methods, ${output.length} bytes)`);
}
