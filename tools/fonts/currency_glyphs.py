"""Writes which currency-symbol characters each bundled font lacks, for the app's money text.

    python3 tools/fonts/currency_glyphs.py

Reads every symbol in `packages/domain/src/money/currency.ts` and the cmap of every font in
`apps/mobile/assets/fonts`, and writes `apps/mobile/src/ui/type/currency-glyphs.generated.ts`.
A symbol a look's display face cannot draw is drawn in the system face instead. Run it after
`build_fonts.py` or after adding a currency.
"""

import re
from pathlib import Path

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
FONTS = ROOT / "apps/mobile/assets/fonts"
CURRENCY = ROOT / "packages/domain/src/money/currency.ts"
OUT = ROOT / "apps/mobile/src/ui/type/currency-glyphs.generated.ts"


def family_of(font: TTFont, path: Path) -> str:
    """The family `fontFamily` names the file by: its file name before the style or "-Variable"."""
    return path.stem.replace("-Variable", "")


def main() -> None:
    symbols = re.findall(r"^\s+[A-Z]{3}: \[\d, '([^']+)'", CURRENCY.read_text(), re.M)
    chars = sorted({c for s in symbols for c in s if not c.isascii()})
    lines = []
    for path in sorted(FONTS.glob("*.ttf")):
        if path.stem.startswith("MaterialSymbols"):
            continue
        cmap = TTFont(path).getBestCmap()
        missing = "".join(c for c in chars if ord(c) not in cmap)
        lines.append(f"  '{family_of(TTFont(path), path)}': '{missing}',")
    OUT.write_text(
        "// Generated by tools/fonts/currency_glyphs.py from the bundled fonts. Do not edit.\n\n"
        "/** Per font family, the non-ASCII currency-symbol characters it cannot draw. */\n"
        "export const MISSING_CURRENCY_GLYPHS: Readonly<Record<string, string>> = {\n"
        + "\n".join(lines)
        + "\n};\n"
    )


if __name__ == "__main__":
    main()
