"""Writes the line height iOS gives each bundled font, for display text set tighter than that.

    python3 tools/fonts/font_metrics.py

Reads the hhea ascender, descender and line gap of every font in `apps/mobile/assets/fonts` (the
metrics Core Text lays a line out with) and writes `apps/mobile/src/ui/type/font-metrics.generated.ts`.
Run it after `build_fonts.py`.
"""

from pathlib import Path

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
FONTS = ROOT / "apps/mobile/assets/fonts"
OUT = ROOT / "apps/mobile/src/ui/type/font-metrics.generated.ts"


def main() -> None:
    lines = []
    for path in sorted(FONTS.glob("*.ttf")):
        if path.stem.startswith("MaterialSymbols"):
            continue
        font = TTFont(path)
        em = font["head"].unitsPerEm
        hhea = font["hhea"]
        line = (hhea.ascent - hhea.descent + hhea.lineGap) / em
        lines.append(f"  '{path.stem.replace('-Variable', '')}': {line:.4f},")
    OUT.write_text(
        "// Generated by tools/fonts/font_metrics.py from the bundled fonts. Do not edit.\n\n"
        "/** Per font family, the height of one line iOS sets it in, in ems. */\n"
        "export const FONT_LINE_HEIGHT: Readonly<Record<string, number>> = {\n"
        + "\n".join(lines)
        + "\n};\n"
    )


if __name__ == "__main__":
    main()
